// Regenerates packages/chain/src/abis.ts from Foundry artifacts. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const out = resolve("packages/contracts/out");
const contracts = ["RetirementPool", "CarbonReceipt", "DCO2", "TestUSDC", "ERC8004ReputationAdapter"];
let src = "// Generated by scripts/gen-abis.mjs from packages/contracts/out. Do not edit.\n\n";
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(resolve(out, `${name}.sol`, `${name}.json`), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1);
  src += `export const ${id}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(resolve("packages/chain/src/abis.ts"), src);
console.log("wrote packages/chain/src/abis.ts");
